-- Схема и учебные справочники «Автоимперии» из SQLite.
CREATE SCHEMA autoimperia;
REVOKE ALL ON SCHEMA autoimperia FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO autoimperia, pg_catalog;

CREATE TABLE clients (
            client_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            phone TEXT NOT NULL,
            email TEXT,
            bonus_balance DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            notes TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE vehicles (
            vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id INTEGER NOT NULL,
            brand TEXT NOT NULL,
            model TEXT NOT NULL,
            prod_year INTEGER,
            plate_number TEXT,
            vin_code TEXT,
            mileage INTEGER DEFAULT 0,
            notes TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (client_id) REFERENCES clients(client_id) ON DELETE CASCADE ON UPDATE CASCADE
        );

CREATE TABLE service_categories (
            category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            category_name TEXT NOT NULL,
            icon_class TEXT,
            description TEXT,
            sort_order INTEGER NOT NULL DEFAULT 0
        );

CREATE TABLE services (
            service_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            category_id INTEGER NOT NULL,
            title TEXT NOT NULL,
            price DOUBLE PRECISION NOT NULL,
            duration_min INTEGER NOT NULL DEFAULT 30,
            required_bay TEXT NOT NULL DEFAULT 'lift',
            is_active INTEGER NOT NULL DEFAULT 1,
            is_popular INTEGER NOT NULL DEFAULT 0,
            description TEXT,
            upsell_recommendation TEXT,
            FOREIGN KEY (category_id) REFERENCES service_categories(category_id) ON DELETE RESTRICT ON UPDATE CASCADE
        );

CREATE TABLE work_bays (
            bay_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            bay_name TEXT NOT NULL,
            bay_type TEXT NOT NULL DEFAULT 'lift',
            max_weight DOUBLE PRECISION NOT NULL DEFAULT 4.0,
            is_active INTEGER NOT NULL DEFAULT 1
        );

CREATE TABLE staff_users (
            user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            full_name TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'master',
            phone TEXT,
            is_active INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE appointments (
            appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            booking_code TEXT NOT NULL UNIQUE,
            client_id INTEGER NOT NULL,
            vehicle_id INTEGER NOT NULL,
            bay_id INTEGER,
            master_id INTEGER,
            visit_date DATE NOT NULL,
            start_time TIME NOT NULL,
            end_time TIME NOT NULL,
            total_price DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            parts_price DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            discount_amount DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            payment_status TEXT NOT NULL DEFAULT 'unpaid',
            paid_amount DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            status TEXT NOT NULL DEFAULT 'new',
            client_comment TEXT,
            internal_notes TEXT,
            cancel_reason TEXT,
            parts_included INTEGER NOT NULL DEFAULT 1,
            parts_grade TEXT NOT NULL DEFAULT 'oem',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (client_id) REFERENCES clients(client_id) ON DELETE CASCADE ON UPDATE CASCADE,
            FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id) ON DELETE CASCADE ON UPDATE CASCADE,
            FOREIGN KEY (bay_id) REFERENCES work_bays(bay_id) ON DELETE SET NULL ON UPDATE CASCADE,
            FOREIGN KEY (master_id) REFERENCES staff_users(user_id) ON DELETE SET NULL ON UPDATE CASCADE
        );

CREATE TABLE appointment_services (
            item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            appointment_id INTEGER NOT NULL,
            service_id INTEGER NOT NULL,
            price_at_order DOUBLE PRECISION NOT NULL,
            parts_cost DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            duration_min INTEGER NOT NULL,
            FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id) ON DELETE CASCADE ON UPDATE CASCADE,
            FOREIGN KEY (service_id) REFERENCES services(service_id) ON DELETE RESTRICT ON UPDATE CASCADE
        );

CREATE TABLE payments (
            payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            appointment_id INTEGER NOT NULL,
            payment_code TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL,
            payment_type TEXT NOT NULL DEFAULT 'deposit_prepay',
            payment_method TEXT NOT NULL DEFAULT 'sbp',
            status TEXT NOT NULL DEFAULT 'pending',
            fiscal_receipt_number TEXT,
            fiscal_qr_payload TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id) ON DELETE CASCADE ON UPDATE CASCADE
        );

CREATE TABLE vehicle_market_data (
            spec_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            brand TEXT NOT NULL,
            model TEXT NOT NULL,
            year_from INTEGER NOT NULL,
            year_to INTEGER NOT NULL,
            engine_desc TEXT NOT NULL,
            oil_type TEXT NOT NULL,
            oil_liters DOUBLE PRECISION NOT NULL,
            oil_price_per_l DOUBLE PRECISION NOT NULL,
            oil_filter_oem TEXT NOT NULL,
            oil_filter_price DOUBLE PRECISION NOT NULL,
            air_filter_price DOUBLE PRECISION NOT NULL,
            cabin_filter_price DOUBLE PRECISION NOT NULL,
            brake_pads_front_oem TEXT NOT NULL,
            brake_pads_front_price DOUBLE PRECISION NOT NULL,
            brake_pads_analog_price DOUBLE PRECISION NOT NULL,
            brake_discs_front_price DOUBLE PRECISION NOT NULL,
            spark_plug_price_set DOUBLE PRECISION NOT NULL,
            coolant_liters DOUBLE PRECISION NOT NULL,
            coolant_price DOUBLE PRECISION NOT NULL,
            labor_multiplier DOUBLE PRECISION NOT NULL DEFAULT 1.00,
            market_source TEXT NOT NULL DEFAULT 'Autodoc / Exist / Zzap / Emex API',
            last_parsed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE promotions (
            promo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code TEXT NOT NULL UNIQUE,
            discount_type TEXT NOT NULL DEFAULT 'percent',
            discount_val DOUBLE PRECISION NOT NULL,
            min_order_sum DOUBLE PRECISION NOT NULL DEFAULT 0.00,
            is_active INTEGER NOT NULL DEFAULT 1
        );

CREATE INDEX idx_clients_phone ON clients(phone);

CREATE INDEX idx_vehicles_brand ON vehicles(brand);

CREATE INDEX idx_vehicles_plate ON vehicles(plate_number);

CREATE INDEX idx_services_category ON services(category_id);

CREATE INDEX idx_app_date ON appointments(visit_date);

CREATE INDEX idx_app_start_time ON appointments(start_time);

CREATE INDEX idx_app_status ON appointments(status);

CREATE INDEX idx_app_serv_app ON appointment_services(appointment_id);

CREATE INDEX idx_pay_app ON payments(appointment_id);

CREATE INDEX idx_market_brand_model ON vehicle_market_data(brand, model);

CREATE TABLE IF NOT EXISTS client_accounts (
    client_id INTEGER PRIMARY KEY REFERENCES clients(client_id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS appointment_odometer (
    appointment_id INTEGER PRIMARY KEY REFERENCES appointments(appointment_id) ON DELETE CASCADE,
    kilometers INTEGER NOT NULL CHECK (kilometers BETWEEN 1 AND 2000000)
);
CREATE INDEX IF NOT EXISTS appointments_client_visit ON appointments(client_id, visit_date DESC, appointment_id DESC);
CREATE INDEX IF NOT EXISTS appointment_services_by_visit ON appointment_services(appointment_id);
CREATE INDEX IF NOT EXISTS vehicles_by_client ON vehicles(client_id);

CREATE UNIQUE INDEX client_accounts_email_lower ON client_accounts (lower(email));

